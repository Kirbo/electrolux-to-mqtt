#!/bin/sh
# secrets-local-config.sh — (re)generate the gitignored fnox.local.toml from fnox.toml.
#
# fnox.toml carries no identity (CI injects FNOX_AGE_KEY_FILE). On a maintainer
# machine the identity lives in the OS keychain (`pnpm secrets:setup` stores it), and
# fnox.local.toml points every age provider at it. fnox merges a provider WHOLE, not
# field by field, so the local file must repeat each provider's recipients — this
# script copies them, which is why it re-runs whenever fnox.toml may have changed
# (secrets:setup, secrets:rotate-ci, and the post-merge/post-checkout/post-rewrite git
# hooks). A stale copy would encrypt new values to old recipients.
#
# Writes no secret. A machine without fnox.local.toml (CI, contributors) is untouched
# unless --force: `secrets:setup` passes it to create the file the first time.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="${ROOT}/fnox.toml"
DST="${ROOT}/fnox.local.toml"
SERVICE="electrolux-to-mqtt.fnox"
KEY="E2M_AGE_IDENTITY"

if [ ! -f "${DST}" ] && [ "${1:-}" != "--force" ]; then
  exit 0
fi

tmp="${DST}.tmp.$$"
{
  echo "# GENERATED by scripts/secrets-local-config.sh from fnox.toml — do not edit, do not commit."
  echo "# Points every age provider at the maintainer identity in the OS keychain."
  echo ""
  echo "[providers.keychain]"
  echo "type = \"keychain\""
  echo "service = \"${SERVICE}\""
  echo ""
  awk -v key="${KEY}" '
    /^\[/ { inage = ($0 ~ /^\[providers\.age_[a-z0-9_]+\]/) }
    inage {
      print
      if ($0 ~ /^type = "age"/) print "identity = { provider = \"keychain\", value = \"" key "\" }"
    }
  ' "${SRC}"
  echo ""
  echo "[secrets]"
  echo "${KEY} = { provider = \"keychain\", value = \"${KEY}\", env = false }"
} >"${tmp}"
mv "${tmp}" "${DST}"
echo "secrets: regenerated fnox.local.toml from fnox.toml"
